"""
Adversarial verification + COMBINED measurement of the three Detector C
proposals (2026-07-02):

  NAMES   gate (d): a name-only identity cluster (no D.2/3/4/5 edge) never
          confers a C consensus vote; takedown carve-out retained.
          (name_only_cluster_audit.py)
  DOMAINS K=2 + takedown carve-out: a D.5 domain edge survives only if the
          domain bucket has <= 2 distinct organizer name token-sets; clusters
          re-componentized; takedown campaigns keep their shipped C flag.
          (d5_domain_coherence.py)
  HANDLES GUARDRAIL-2 (fuzzy-distinct swept payment-handle reuse as an
          ADDITIVE C fire). The HANDLES proposal itself recommends NOT
          adopting this; measured here both ways for the interaction check.
          (d4_handle_enrichment.py / d4_swept_handles.csv)

Method: reuses the d5_domain_coherence.py reconstruction (bucket rebuild
mirroring detector_D_identity.py, edge reconstruction inside shipped
clusters, consensus recompute per combined_hardened_consensus.py), asserts
the no-gate variant reproduces the canonical tier EXACTLY, asserts each
single-proposal variant reproduces the numbers reported by its proposal
script, then composes them.

Composition semantics (order-free, single pass):
  1. Delete D.5 edges on incoherent domains (>2 distinct organizer name-sets).
  2. Recompute connected components inside each shipped cluster.
  3. C0' = campaign in a >= 2-member surviving component; a taken-down
     campaign keeps its shipped C0 even if isolated (domain carve-out).
  4. NAMES(d): c_rule' = component contains a surviving deterministic edge
     (D.2/3/4 always survive; D.5 only on coherent domains). The
     cross-platform / >= 3-member fallbacks are REMOVED entirely.
  5. C_hard' = C0' and (c_rule' or takedown)  [takedown carve-out].
  6. A carve-out re-evaluated on the GATED campaign-level deterministic-C
     signal (same as d5_domain_coherence.py).
  7. Optional HANDLES gr2: campaign with a fuzzy-distinct swept-handle edge
     gets C_hard' = 1 and counts as corroborated via C.
  corroborated' = takedown OR rep_hard OR (C0' and c_rule') OR handle-edge.

Also verifies two claims not printed by the proposal scripts:
  - NAMES: "16 of the 109 takedowns-in-tier are C-pivotal via name-only
    clusters and survive only via the takedown carve-out."
  - HANDLES: "10 of the 42 shipped D.4 campaigns rest on LLM-extraction
    artifacts (Instagram handles / non-literal paypal.me strings)."

READ-ONLY w.r.t. canonical files. Output: printed report +
combined_c_gates_verification.txt next to this script.
"""
