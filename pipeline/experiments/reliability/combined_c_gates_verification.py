def handle_is_artifact(u, h):
    """True if handle h on campaign u is an LLM-extraction artifact:
    not literally present in title+description, or an @handle in an
    Instagram context."""
    text = (url_desc.get(u) or "").lower()
    core = h.lstrip("@").lower()
    if h.startswith("@"):
        for m in re.finditer(re.escape(core), text):
            lo, hi = max(0, m.start() - 100), min(len(text), m.end() + 100)
