# ======================================================= consensus recompute
def gated_sigs(sigs, e, domain_gate):
    if not domain_gate or "D.5_domain" not in sigs:
        return sigs
    if d5_edge_domains.get(e, set()) & ALLOWED_DOMAINS:
        return sigs
    return sigs - {"D.5_domain"}

def run_variant(label, names_gate=False, domain_gate=False, dom_carveout=False,
                handles_gr2=False):
    C0v, cinfo = {}, {}
    camp_det = collections.defaultdict(bool)
    for cid, mem in clusters.items():
        parent = {u: u for u in mem}
        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]; x = parent[x]
            return x
        for e, s in cluster_edges[cid]:
            if gated_sigs(s, e, domain_gate):
                ra, rb = find(e[0]), find(e[1])
                if ra != rb: parent[ra] = rb
        comps = collections.defaultdict(set)
        for u in mem: comps[find(u)].add(u)
        for comp in comps.values():
            if len(comp) < 2:
                for u in comp:
                    if dom_carveout and u in takedown_urls:
                        C0v[u] = True; cinfo[u] = (1, 1, False)
                    else:
                        C0v[u] = False
                continue
            plats = {url_platform.get(u, "?") for u in comp}
            has_det = False
            for e, s in cluster_edges[cid]:
                if e[0] in comp and e[1] in comp:
                    gs = gated_sigs(s, e, domain_gate)
                    if gs & DET_SIGS:
                        has_det = True
                        camp_det[e[0]] = camp_det[e[1]] = True
            for u in comp:
                C0v[u] = True
                cinfo[u] = (len(comp), len(plats), has_det)

    res = {}
    for u, cr in canon.items():
        takedown = cr["takedown"] == "1"
        C0 = C0v.get(u, False)
        if C0:
            size, nplat, has_det = cinfo[u]
            c_rule = has_det if names_gate else (has_det or nplat >= 2 or size >= 3)
        else:
            c_rule = False
        C_hard = C0 and (c_rule or takedown)
        handle_edge = handles_gr2 and u in gr2_urls
        if handle_edge:
            C_hard = True
        c_det = C0 and camp_det.get(u, False)
        rep, heur = cr["rep_hard"] == "1", cr["heur_hard"] == "1"
        A_hard = rep or heur
        if (takedown or c_det) and cr["A0"] == "1" and not A_hard:
            A_hard = True
        B_hard = cr["B_hard"] == "1"
        fraud = (int(A_hard) + int(B_hard) + int(C_hard)) >= 2
        corrob = takedown or rep or (C0 and c_rule) or handle_edge
        res[u] = dict(C0=C0, C_hard=C_hard, c_rule=c_rule, fraud=fraud,
                      corrob=corrob, takedown=takedown, rep=rep, c_det=c_det,
                      A=A_hard, B=B_hard,
                      carveout_only=(C0 and not c_rule and takedown and not handle_edge))
    return label, res

def report(label, res):
    r = list(res.values())
    C0n = sum(x["C0"] for x in r)
    Chn = sum(x["C_hard"] for x in r)
    fr = [x for x in r if x["fraud"]]
    fr_u = [u for u, x in res.items() if x["fraud"]]
    corr = sum(x["corrob"] for x in fr)
    txt = len(fr) - corr
    ggf = [u for u in fr_u if canon[u]["platform"] == "GoGetFunding"]
    ggf_txt = sum(1 for u in ggf if not res[u]["corrob"])
    td_in = sum(1 for x in fr if x["takedown"])
    rep_in = sum(1 for x in fr if x["rep"])
    lost = [u for u, x in res.items() if canon[u]["fraud_hard"] == "1" and not x["fraud"]]
    gained = [u for u, x in res.items() if canon[u]["fraud_hard"] == "0" and x["fraud"]]
    lost_td = sum(1 for u in lost if canon[u]["takedown"] == "1")
    lost_rep = sum(1 for u in lost if canon[u]["rep_hard"] == "1")
    p()
    p(f"---- {label} " + "-" * max(1, 66 - len(label)))
    p(f"  C consensus-fires:  {Chn:,}  (canonical 3,708; delta {Chn-3708:+,})   [C0 {C0n:,}]")
    p(f"  fraud tier:         {len(fr):,}  (canonical 1,078; delta {len(fr)-1078:+,})"
      f"   [lost {len(lost)}, gained {len(gained)}]")
    p(f"    corroborated:     {corr:,} (canonical 619)   text-only: {txt:,} (canonical 459)"
      f"  [{100*txt/len(fr):.1f}% text-only]")
    p(f"  GGF fraud:          {len(ggf):,} (canonical 793)   text-only {ggf_txt:,}"
      f" (canonical 397)  [{100*ggf_txt/len(ggf):.1f}%]")
    p(f"  takedowns in tier:  {td_in} / 109   (lost: {lost_td})")
    p(f"  rep_hard fraud in tier: {rep_in}   rep-corroborated fraud LOST: {lost_rep}")
    return dict(lost=lost, gained=gained, fraud=set(fr_u),
                lost_rep=[u for u in lost if canon[u]["rep_hard"] == "1"])

